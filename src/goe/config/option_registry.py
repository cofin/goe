OPTION_GROUPS: dict[OptionGroupName, tuple[OptionSpec, ...]] = {
    group: tuple(spec for spec in OPTION_SPECS if spec.group == group)
    for group in (
        "common",
        "table_target",
        "partitioning",
        "transport",
        "column_transform",
        "verification",
        "connect",
        "status_report",
        "schema_sync",
        "logmgr",
        "listener",
        "test_mode",
    )
}

_SPEC_BY_NAME: dict[str, OptionSpec] = {spec.name: spec for spec in OPTION_SPECS}


def get_option_spec(name: str) -> OptionSpec | None:
    """Return the OptionSpec for the given canonical option name, or None if not found."""
    return _SPEC_BY_NAME.get(name)


def get_option_specs_for_group(group: OptionGroupName) -> tuple[OptionSpec, ...]:
    """Return all OptionSpec entries belonging to the specified option group."""
    return OPTION_GROUPS.get(group, ())


def options_for_command(command: str, *, include_deprecated: bool = False) -> tuple[OptionSpec, ...]:
    """Return all OptionSpec entries applicable to the specified CLI command."""
    return tuple(
        spec for spec in OPTION_SPECS if command in spec.commands and (include_deprecated or not spec.deprecated)
    )


def listener_alias_map() -> dict[str, str]:
    """Return a mapping of Listener payload keys to canonical OptionSpec names."""
    aliases: dict[str, str] = {
        spec.listener_alias: spec.name for spec in OPTION_SPECS if spec.listener_alias is not None
    }
    aliases.setdefault("owner_table", "table")
    aliases.setdefault("reset_Target_table", "reset_backend_table")
    aliases.setdefault("reuse_Target_table", "reuse_backend_table")
    aliases.setdefault("create_Target_db", "create_backend_db")
    return aliases
